    // AC2: the global usage rollups (ADR 0031). Buckets are classes without value equality, so each
    // is compared member-wise — the whole point is that a dropped counter cannot slip through.
    [Fact]
    public void UsageRollupState_RoundTripsFieldForField()
    {
        var expected = GoldenStates.UsageRollup();
        var actual = Restore<UsageRollupState>(UsageRollupStateBlob);

        AssertTokens(expected.HourlyTokens["h"], actual.HourlyTokens["h"]);
        AssertTokens(expected.DailyTokens["d"], actual.DailyTokens["d"]);
        AssertTools(expected.HourlyTools["h"], actual.HourlyTools["h"]);
        AssertTools(expected.DailyTools["d"], actual.DailyTools["d"]);
    }

    private static void AssertTokens(TokenBucket expected, TokenBucket actual)
    {
        Assert.Equal(expected.BucketUnixSeconds, actual.BucketUnixSeconds);
        Assert.Equal(expected.Application, actual.Application);
        Assert.Equal(expected.Provider, actual.Provider);
        Assert.Equal(expected.Model, actual.Model);
        Assert.Equal(expected.UserKey, actual.UserKey);
        Assert.Equal(expected.InputTokens, actual.InputTokens);
        Assert.Equal(expected.OutputTokens, actual.OutputTokens);
        Assert.Equal(expected.CachedInputTokens, actual.CachedInputTokens);
        Assert.Equal(expected.ReasoningOutputTokens, actual.ReasoningOutputTokens);
        Assert.Equal(expected.CallCount, actual.CallCount);
        Assert.Equal(expected.ErrorCount, actual.ErrorCount);
    }

    private static void AssertTools(ToolBucket expected, ToolBucket actual)
    {
        Assert.Equal(expected.BucketUnixSeconds, actual.BucketUnixSeconds);
        Assert.Equal(expected.Application, actual.Application);
        Assert.Equal(expected.ToolName, actual.ToolName);
        Assert.Equal(expected.UserKey, actual.UserKey);
        Assert.Equal(expected.Count, actual.Count);
        Assert.Equal(expected.ErrorCount, actual.ErrorCount);
    }

