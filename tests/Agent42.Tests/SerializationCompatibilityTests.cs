    private static readonly IServiceProvider Services = BuildSerializerServices();

    private static IServiceProvider BuildSerializerServices()
    {
        var services = new ServiceCollection();
        services.AddSerializer(b => b.AddAssembly(typeof(AgentGrainState).Assembly));
        return services.BuildServiceProvider();
    }

