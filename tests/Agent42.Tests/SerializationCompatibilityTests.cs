/// <summary>
/// Golden-blob compatibility for every persisted grain-state root (ADR 0039). Each blob was
/// serialized on the pre-feature-folder layout and committed verbatim; the tests deserialize it with
/// today's types and assert field-for-field against <see cref="GoldenStates"/>.
///
/// <para><b>What these blobs actually prove — established by mutation check, not by assumption
/// (ADR 0039).</b> Three mutations were run against this fixture:</para>
/// <list type="bullet">
///   <item>Renumbering one <c>[Id(n)]</c> (<c>StoredModel.SupportsSpeech</c> 6 → 7): <b>caught</b>.</item>
///   <item>Changing an <c>[Alias]</c> string (<c>StoredMcpServer</c>): <b>NOT caught</b>.</item>
///   <item>Moving a serialized type to another namespace (<c>McpOAuthPending</c> and its grain):
///         <b>NOT caught</b>.</item>
/// </list>
/// <para>So these blobs guard <c>[Id(n)]</c> numbering and member drift, and nothing else. Do not
/// read them as an alias or namespace guard. Note in particular that a blob visibly contains strings
/// like <c>ReadOnlyListInterfaceCodec`1[[Agent42.Agents.StoredMcpServer]]</c> for interface-typed
/// members — that token looks alias-derived, but the alias mutation proves it is not load-bearing on
/// the read path.</para>
///
/// <para><b>Do NOT conclude from the third row that a namespace move is safe.</b> That was concluded
/// once, and it was wrong. This class exercises Orleans' BINARY serializer, which carries grain-to-grain
/// calls. Grain STATE goes to Cosmos through <c>JsonGrainStorageSerializer</c>, which embeds the full
/// CLR type name in every document, so a namespace change there is catastrophic and invisible here.
/// <see cref="GrainStorageSerializerTests"/> is the test that covers the persistence path; these two
/// files are not interchangeable and neither substitutes for the other.</para>
///
/// <para><b>What they do NOT prove.</b> A hand-built <see cref="Serializer{T}"/> is not the
/// <c>IGrainStorageSerializer</c> that <c>AddCosmosGrainStorage</c> installs in
/// <c>src/Agent42.Backend/Program.cs</c> — that question is settled in
/// <see cref="GrainStorageSerializerTests"/> instead, and the answer is JSON with <c>$type</c>
/// discriminators. Between them, <see cref="GrainIdentityTests"/> guards how a document is FOUND
/// (<c>GrainId</c> keys it) and <see cref="GrainStorageSerializerTests"/> guards whether it can be
/// READ. This file guards neither.</para>
///
/// <para>The fixture is committed, never regenerated by the test. A test that writes its own
/// expectation when absent would pass by construction and guard nothing.</para>
/// </summary>
public sealed class SerializationCompatibilityTests
