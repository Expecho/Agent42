#!/usr/bin/env node
// Code-shape measurement: method length, parameter count and class size over the C# tree.
// A REPORT tool (clean-code programme, plan cc-01): it adds no gate. The gates are SonarAnalyzer S138/S107
// (ADR 0149), which count a few lines differently, so this output is for orientation and the build is the verdict.
//
// Usage:
//   node .agentic/scripts/code-shape.mjs [--root <dir>] [--top <n>] [--json <file>] [--all]
//     --root  repo root to scan (default: cwd). Scans <root>/src, <root>/tools and <root>/tests as
//             three SEPARATE sections; `tests/` is reported because the Sonar analyzer is a
//             GlobalPackageReference and a rule enabled later applies to every project.
//     --top   rows per markdown table (default 15).
//     --json  also write machine-readable JSON to <file> (the committed baseline is
//             .agentic/code-shape-baseline.json). Without --all the JSON lists only entries above a
//             reporting floor (methods >= 40 lines of code or >= 5 params; classes >= 400 lines of
//             code or ctor >= 5 params): the full tree would be a megabyte of noise.
//     --all   no floor.
//
// METRIC DEFINITIONS (aim to match Sonar S138 / S107, which ADR 0149 enforces):
//   * Method length is LINES OF CODE: the non-blank, non-comment lines from the line the method NAME
//     is on to the line of its closing `}` (or the `;` ending an expression body), inclusive.
//     Attribute lines above the name are not counted. A line holding only a string literal (a
//     multi-line verbatim or raw string) IS code; `#region`/`#if` directive lines are NOT.
//     `span` is the raw first-to-last line count, reported as a second column only.
//   * Params: top-level commas in the parameter list + 1, attributes and default values ignored,
//     commas inside `<>`, `()`, `[]` do not count. A primary constructor (`class X(A a, B b)`,
//     `record R(int A)`) feeds the CLASS's ctorParams; it is not a method entry, so it is absent from the
//     per-method params table.
//   * Local functions and lambdas are NOT measured separately: their lines count toward the
//     enclosing method.
//   * Methods include constructors, operators, and body-less declarations (interface/abstract
//     methods: loc = their declaration lines), because S107 applies to those too.
//   * Method key = `<file>::<Namespace>.<Outer>.<Type>.<Method>(<param types>)`, with `#2`, `#3` on a
//     true duplicate. Never file:line: a line number goes stale on the next edit (`line` is
//     informational only).
//   * Class = a type declaration; partials are aggregated by namespace + type path (files = the file
//     set, loc/span summed, ctorParams = max over all constructors and the primary ctor, members =
//     methods + ctors + properties + fields/events).
//   * Excluded: obj/, bin/, node_modules/, generated files (*.g.cs, *.designer.cs, *.generated.cs,
//     `<auto-generated` header).
//
// It is a comment/string-aware brace scanner, not a parser. Known limits: it assumes well-formed C#,
// does not track `<`/`>` as brackets outside parameter lists, and top-level-statement files are only
// scanned for the types they declare. The xUnit fixture test (CodeShapeToolTests) is its coverage:
// the Node script is not covered by coverlet.
//
// No npm dependencies, matching the other scripts here.
import { readFileSync, readdirSync, writeFileSync, existsSync, statSync } from "node:fs";
import { join, resolve, relative } from "node:path";
import { execFileSync } from "node:child_process";

// ---------------------------------------------------------------- argument parsing
function parseArgs(argv) {
  const opts = { root: process.cwd(), top: 15, json: null, all: false };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === "--root") opts.root = resolve(argv[++i]);
    else if (a === "--top") opts.top = Number(argv[++i]);
    else if (a === "--json") opts.json = argv[++i];
    else if (a === "--all") opts.all = true;
    else {
      console.error(`unknown argument: ${a}`);
      process.exit(2);
    }
  }
  return opts;
}

// ---------------------------------------------------------------- masking
// Replace comments with spaces and string/char literal CONTENT with `s`, keeping every newline and the
// total length, so offsets and line numbers in the masked text equal those of the source and no brace
// or paren inside a string or comment can confuse the scanner.
function skipHole(src, k) {
  // src[k] === '{' opening an interpolation hole; returns the index just past its closing '}'.
  const n = src.length;
  let depth = 1;
  k++;
  while (k < n && depth > 0) {
    const ch = src[k];
    if (ch === "{") depth++;
    else if (ch === "}") depth--;
    else if (ch === '"') {
      k++;
      while (k < n && src[k] !== '"') k += src[k] === "\\" ? 2 : 1;
    } else if (ch === "'") {
      k += src[k + 1] === "\\" ? 3 : 2;
    }
    k++;
  }
  return k;
}

function stringEnd(src, i) {
  // src[i] starts a string literal (optionally prefixed by $ and/or @); returns the end index (exclusive).
  const n = src.length;
  let j = i;
  let interp = false;
  let verb = false;
  while (src[j] === "$" || src[j] === "@") {
    if (src[j] === "$") interp = true;
    else verb = true;
    j++;
  }
  let q = 0;
  while (src[j + q] === '"') q++;
  if (!verb && q >= 3) {
    const idx = src.indexOf('"'.repeat(q), j + q);
    return idx < 0 ? n : idx + q;
  }
  if (!verb && q === 2) return j + 2;
  let k = j + 1;
  if (verb) {
    while (k < n) {
      if (src[k] === '"') {
        if (src[k + 1] === '"') {
          k += 2;
          continue;
        }
        break;
      }
      if (interp && src[k] === "{") {
        k = src[k + 1] === "{" ? k + 2 : skipHole(src, k);
        continue;
      }
      k++;
    }
    return k + 1;
  }
  while (k < n && src[k] !== '"' && src[k] !== "\n") {
    if (src[k] === "\\") {
      k += 2;
      continue;
    }
    if (interp && src[k] === "{") {
      k = src[k + 1] === "{" ? k + 2 : skipHole(src, k);
      continue;
    }
    k++;
  }
  return k + 1;
}

function mask(src) {
  const n = src.length;
  const out = new Array(n);
  const fill = (a, b, ch) => {
    for (let k = a; k < b && k < n; k++) out[k] = src[k] === "\n" || src[k] === "\r" ? src[k] : ch;
  };
  let i = 0;
  let lineStart = true;
  while (i < n) {
    const c = src[i];
    const d = src[i + 1];
    if (c === "\n") {
      out[i++] = c;
      lineStart = true;
    } else if (c === " " || c === "\t" || c === "\r") {
      out[i++] = c;
    } else if (c === "/" && d === "/") {
      const j = src.indexOf("\n", i);
      const end = j < 0 ? n : j;
      fill(i, end, " ");
      i = end;
    } else if (c === "/" && d === "*") {
      const j = src.indexOf("*/", i + 2);
      const end = j < 0 ? n : j + 2;
      fill(i, end, " ");
      i = end;
      lineStart = false;
    } else if (c === "#" && lineStart) {
      const j = src.indexOf("\n", i);
      const end = j < 0 ? n : j;
      fill(i, end, " ");
      i = end;
    } else if (c === '"' || ((c === "$" || c === "@") && /^[$@]+"/.test(src.slice(i, i + 5)))) {
      const end = Math.min(stringEnd(src, i), n);
      fill(i, end, "s");
      i = end;
      lineStart = false;
    } else if (c === "'") {
      let k = i + 1;
      if (src[k] === "\\") k += 2;
      while (k < n && src[k] !== "'" && src[k] !== "\n") k++;
      const end = Math.min(k + 1, n);
      fill(i, end, "s");
      i = end;
      lineStart = false;
    } else {
      out[i++] = c;
      lineStart = false;
    }
  }
  return out.join("");
}

// ---------------------------------------------------------------- header helpers
// Replace every balanced [...] group (attributes, array ranks, indexers) with spaces of equal length,
// keeping newlines, so offsets into the header are unchanged.
function blankBrackets(h) {
  const out = h.split("");
  let depth = 0;
  for (let i = 0; i < h.length; i++) {
    const ch = h[i];
    if (ch === "[") depth++;
    if (depth > 0 && ch !== "\n" && ch !== "\r") out[i] = " ";
    if (ch === "]" && depth > 0) depth--;
  }
  return out.join("");
}

function splitParams(inner) {
  if (!inner.trim()) return [];
  const parts = [];
  let depth = 0;
  let cur = "";
  for (let i = 0; i < inner.length; i++) {
    const ch = inner[i];
    if ("([{<".includes(ch)) depth++;
    else if (")]}".includes(ch)) depth--;
    else if (ch === ">" && inner[i - 1] !== "=") depth--;
    if (ch === "," && depth === 0) {
      parts.push(cur);
      cur = "";
    } else cur += ch;
  }
  parts.push(cur);
  return parts.map((p) => p.trim());
}

function paramType(p) {
  const noDefault = p.split("=")[0];
  return noDefault
    .replace(/\s+[@\w]+\s*$/, "")
    .replace(/\s+/g, " ")
    .replace(/\s*,\s*/g, ",")
    .trim();
}

function matchingParen(h, open) {
  let depth = 0;
  for (let i = open; i < h.length; i++) {
    if (h[i] === "(") depth++;
    else if (h[i] === ")" && --depth === 0) return i;
  }
  return h.length;
}

const TYPE_RE =
  /(?:^|\s)(?:record\s+(?:class|struct)|class|struct|interface|enum|record)\s+([A-Za-z_]\w*)/;
const NAME_RE = /(operator\s*[^\s\w(]+|operator\s+[\w.<>?]+|~?[A-Za-z_]\w*)\s*(?:<[^()]*>)?\s*$/;

// Parses a member header (attributes already blanked) as a method/ctor/operator, or returns null.
const MODIFIERS = new Set([
  "public", "private", "protected", "internal", "static", "async", "virtual", "override", "abstract", "sealed",
  "extern", "unsafe", "new", "partial", "readonly", "ref", "in", "out", "const", "volatile", "required", "file",
]);

// Parses a member header (attributes already blanked) as a method/ctor/operator, or returns null.
// The parameter list is the first `(` that follows a NAME: a tuple return type (`static (int, int) M(...)`,
// `Task<(int A, int B)> M(...)`) puts earlier parens in the header that follow a modifier or a `<`.
function parseMethod(h, offset, lineAt) {
  for (let par = h.indexOf("("); par >= 0; par = h.indexOf("(", par + 1)) {
    const pre = h.slice(0, par);
    if (/delegate/.test(pre)) return null;
    const nm = NAME_RE.exec(pre);
    if (!nm || MODIFIERS.has(nm[1])) continue;
    const close = matchingParen(h, par);
    const params = splitParams(h.slice(par + 1, close));
    return {
      name: nm[1].replace(/\s+/g, ""),
      startLine: lineAt(offset + nm.index),
      sig: params.map(paramType).join(","),
      params: params.length,
    };
  }
  return null;
}

// ---------------------------------------------------------------- scanner
function scanFile(file, src) {
  const masked = mask(src);
  const lines = masked.split("\n");
  const lineStarts = [0];
  for (let i = 0; i < masked.length; i++) if (masked[i] === "\n") lineStarts.push(i + 1);
  const lineAt = (idx) => {
    let lo = 0;
    let hi = lineStarts.length - 1;
    while (lo < hi) {
      const mid = (lo + hi + 1) >> 1;
      if (lineStarts[mid] <= idx) lo = mid;
      else hi = mid - 1;
    }
    return lo + 1;
  };
  const pre = [0];
  for (const l of lines) pre.push(pre[pre.length - 1] + (/\S/.test(l) ? 1 : 0));
  const loc = (a, b) => pre[Math.min(b, lines.length)] - pre[a - 1];

  const methods = [];
  const types = [];
  let fileNs = "";
  const mk = (kind, extra = {}) => ({ kind, hdr: 0, p: 0, assign: false, init: 0, pending: null, ...extra });
  const frames = [mk("file")];

  const container = () => frames[frames.length - 1];
  const enclosingType = () => {
    for (let i = frames.length - 1; i >= 0; i--) if (frames[i].typeInfo) return frames[i].typeInfo;
    return null;
  };
  const nsName = () =>
    [fileNs, ...frames.filter((f) => f.kind === "ns").map((f) => f.name)].filter(Boolean).join(".");

  function recordMethod(info, endLine, typeInfo) {
    const rec = {
      file,
      ns: typeInfo ? typeInfo.ns : nsName(),
      type: typeInfo ? typeInfo.path : "",
      name: info.name,
      sig: info.sig,
      params: info.params,
      line: info.startLine,
      loc: loc(info.startLine, endLine),
      span: endLine - info.startLine + 1,
    };
    methods.push(rec);
    if (typeInfo) {
      typeInfo.members++;
      if (info.name === typeInfo.name || info.name === `~${typeInfo.name}`) typeInfo.ctors.push(info.params);
    }
  }

  function closeFrame(i) {
    const f = frames.pop();
    if (f.info) recordMethod(f.info, lineAt(i), f.owner);
    if (f.typeInfo) {
      f.typeInfo.endLine = lineAt(i);
      types.push(f.typeInfo);
    }
    if (frames.length === 0) {
      frames.push(mk("file"));
      return;
    }
    const parent = container();
    parent.hdr = i + 1;
    parent.assign = false;
    parent.p = 0;
    parent.init = 0;
    parent.pending = null;
  }

  function resetMember(top, i) {
    top.hdr = i + 1;
    top.assign = false;
    top.p = 0;
    top.init = 0;
    top.pending = null;
  }

  function endMember(top, i) {
    const h = blankBrackets(masked.slice(top.hdr, i));
    const owner = top.typeInfo && top.kind === "type" ? top.typeInfo : null;
    if (top.pending && top.pending.kind === "method") {
      recordMethod(top.pending.info, lineAt(i), owner);
    } else if (top.pending && top.pending.kind === "prop") {
      if (owner) owner.members++;
    } else if (top.kind === "file") {
      const m = /^\s*namespace\s+([\w.]+)\s*$/.exec(h);
      if (m) fileNs = m[1];
    } else if (owner && h.trim() && !/^\s*=/.test(h) && !/^\s*(delegate|using)\b/.test(h)) {
      const info = top.assign ? null : parseMethod(h, top.hdr, lineAt);
      if (info) recordMethod(info, lineAt(i), owner);
      else owner.members++;
    }
    resetMember(top, i);
  }

  function arrow(top) {
    const h = blankBrackets(masked.slice(top.hdr, top.arrowAt));
    top.assign = true;
    if (top.kind !== "type") return;
    const info = parseMethod(h, top.hdr, lineAt);
    top.pending = info ? { kind: "method", info } : { kind: "prop" };
  }

  function openBrace(top, i) {
    const h = blankBrackets(masked.slice(top.hdr, i));
    const ns = /^\s*namespace\s+([\w.]+)/.exec(h);
    if (ns) {
      frames.push(mk("ns", { name: ns[1], hdr: i + 1 }));
      return;
    }
    const tm = TYPE_RE.exec(h);
    const par = h.indexOf("(");
    if (tm && (par < 0 || tm.index < par)) {
      const name = tm[1];
      const end = tm.index + tm[0].length;
      const typePath = frames
        .filter((f) => f.typeInfo)
        .map((f) => f.typeInfo.name)
        .concat(name)
        .join(".");
      const typeInfo = {
        file,
        ns: nsName(),
        name,
        path: typePath,
        startLine: lineAt(top.hdr + end - name.length),
        endLine: 0,
        members: 0,
        ctors: [],
      };
      const pm = /^\s*(?:<[^(){};]*>)?\s*\(/.exec(h.slice(end));
      if (pm) {
        const open = end + pm[0].length - 1;
        typeInfo.ctors.push(splitParams(h.slice(open + 1, matchingParen(h, open))).length);
      }
      const isEnum = /\benum\s/.test(tm[0]);
      frames.push(mk(isEnum ? "skip" : "type", { typeInfo, hdr: i + 1 }));
      return;
    }
    if (top.kind === "type") {
      const info = parseMethod(h, top.hdr, lineAt);
      if (info) {
        frames.push(mk("body", { info, owner: top.typeInfo, hdr: i + 1 }));
        return;
      }
      top.typeInfo.members++;
    }
    frames.push(mk("skip", { hdr: i + 1 }));
  }

  const n = masked.length;
  for (let i = 0; i < n; i++) {
    const c = masked[i];
    const top = container();
    if (top.kind === "skip" || top.kind === "blk" || top.kind === "body") {
      if (c === "{") frames.push(mk("blk"));
      else if (c === "}") closeFrame(i);
      continue;
    }
    if (c === "(" || c === "[") {
      top.p++;
      continue;
    }
    if (c === ")" || c === "]") {
      if (top.p > 0) top.p--;
      continue;
    }
    if (top.p > 0) continue;
    if (top.assign) {
      if (c === "{") top.init++;
      else if (c === "}") {
        if (top.init > 0) top.init--;
        else closeFrame(i);
      } else if (c === ";" && top.init === 0) endMember(top, i);
      continue;
    }
    if (c === "=") {
      const nx = masked[i + 1];
      if (nx === ">") {
        top.arrowAt = i;
        arrow(top);
        i++;
      } else if (nx === "=") i++;
      else if (!"!<>=".includes(masked[i - 1] ?? " ")) top.assign = true;
    } else if (c === "{") openBrace(top, i);
    else if (c === "}") closeFrame(i);
    else if (c === ";") endMember(top, i);
  }
  return { methods, types, loc, lines: lines.length };
}

// ---------------------------------------------------------------- tree walk + aggregation
const SKIP_DIRS = new Set(["obj", "bin", "node_modules", ".git", ".vs"]);
const GENERATED = /\.(g|generated|designer)\.cs$/i;

function walk(dir, out) {
  for (const name of readdirSync(dir)) {
    if (SKIP_DIRS.has(name)) continue;
    const abs = join(dir, name);
    if (statSync(abs).isDirectory()) walk(abs, out);
    else if (name.endsWith(".cs") && !GENERATED.test(name)) out.push(abs);
  }
}

function measureSection(root, dirName) {
  const base = join(root, dirName);
  const files = [];
  if (existsSync(base)) walk(base, files);
  files.sort();
  const methods = [];
  const classes = new Map();
  const seen = new Map();
  let scanned = 0;
  for (const abs of files) {
    const src = readFileSync(abs, "utf8");
    if (src.slice(0, 600).includes("<auto-generated")) continue;
    scanned++;
    const rel = relative(root, abs).split("\\").join("/");
    const res = scanFile(rel, src);
    for (const m of res.methods) {
      const fq = [m.ns, m.type, m.name].filter(Boolean).join(".");
      let key = `${rel}::${fq}(${m.sig})`;
      const count = (seen.get(key) ?? 0) + 1;
      seen.set(key, count);
      if (count > 1) key += `#${count}`;
      methods.push({ key, file: rel, name: fq, line: m.line, loc: m.loc, span: m.span, params: m.params });
    }
    for (const t of res.types) {
      const ck = [t.ns, t.path].filter(Boolean).join(".");
      const c = classes.get(ck) ?? { key: ck, files: [], loc: 0, span: 0, ctorParams: 0, members: 0 };
      if (!c.files.includes(rel)) c.files.push(rel);
      c.loc += res.loc(t.startLine, t.endLine);
      c.span += t.endLine - t.startLine + 1;
      c.ctorParams = Math.max(c.ctorParams, ...t.ctors, 0);
      c.members += t.members;
      classes.set(ck, c);
    }
  }
  const byKey = (a, b) => (a.key < b.key ? -1 : a.key > b.key ? 1 : 0);
  methods.sort((a, b) => b.loc - a.loc || b.params - a.params || byKey(a, b));
  const classList = [...classes.values()].sort((a, b) => b.loc - a.loc || byKey(a, b));
  return { files: scanned, methods, classes: classList };
}

function summarize(sec) {
  const over = (n) => sec.methods.filter((m) => m.loc > n).length;
  return {
    files: sec.files,
    methods: sec.methods.length,
    methodsOver60: over(60),
    methodsOver80: over(80),
    methodsOver100: over(100),
    methodsWith7PlusParams: sec.methods.filter((m) => m.params >= 7).length,
    classes: sec.classes.length,
    classesOver500Loc: sec.classes.filter((c) => c.loc > 500).length,
    classesWithCtor7Plus: sec.classes.filter((c) => c.ctorParams >= 7).length,
  };
}

// ---------------------------------------------------------------- output
function table(headers, rows) {
  const line = (r) => `| ${r.join(" | ")} |`;
  return [line(headers), line(headers.map(() => "---")), ...rows.map(line)].join("\n");
}

function markdown(report, top) {
  const out = ["# Code shape", "", "Metric: lines of code (non-blank, non-comment); see the script header.", ""];
  for (const [name, sec] of Object.entries(report.sections)) {
    const s = summarize(sec);
    out.push(`## ${name}/`, "");
    out.push(
      `${s.files} files, ${s.methods} methods (>60: ${s.methodsOver60}, >80: ${s.methodsOver80}, >100: ${s.methodsOver100}; ` +
        `>=7 params: ${s.methodsWith7PlusParams}), ${s.classes} classes (>500 loc: ${s.classesOver500Loc}; ctor >=7 params: ${s.classesWithCtor7Plus})`,
      "",
    );
    out.push("Longest methods", "");
    out.push(
      table(
        ["loc", "span", "params", "method"],
        sec.methods.slice(0, top).map((m) => [m.loc, m.span, m.params, `\`${m.name}\` (${m.file}:${m.line})`]),
      ),
      "",
    );
    const wide = [...sec.methods].sort((a, b) => b.params - a.params || b.loc - a.loc).slice(0, top);
    out.push("Most parameters", "");
    out.push(table(["params", "loc", "method"], wide.map((m) => [m.params, m.loc, `\`${m.name}\` (${m.file}:${m.line})`])), "");
    out.push("Largest classes", "");
    out.push(
      table(
        ["loc", "span", "ctor params", "members", "files", "class"],
        sec.classes.slice(0, top).map((c) => [c.loc, c.span, c.ctorParams, c.members, c.files.length, `\`${c.key}\``]),
      ),
      "",
    );
  }
  return out.join("\n");
}

function jsonReport(report, all) {
  const sections = {};
  for (const [name, sec] of Object.entries(report.sections)) {
    sections[name] = {
      summary: summarize(sec),
      methods: all ? sec.methods : sec.methods.filter((m) => m.loc >= 40 || m.params >= 5),
      classes: all ? sec.classes : sec.classes.filter((c) => c.loc >= 400 || c.ctorParams >= 5),
    };
  }
  let measuredAt = "unknown";
  try {
    measuredAt = execFileSync("git", ["rev-parse", "--short", "HEAD"], { cwd: opts.root, encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] }).trim();
  } catch {
    // not a git checkout (a fixture tree): provenance stays "unknown"
  }
  return {
    measuredAt,
    metric: "loc = non-blank non-comment lines from the method name line to its closing line; see code-shape.mjs",
    floor: all ? "none" : "methods loc>=40 or params>=5; classes loc>=400 or ctorParams>=5",
    sections,
  };
}

// ---------------------------------------------------------------- main
const opts = parseArgs(process.argv.slice(2));
const report = { sections: {} };
for (const dir of ["src", "tools", "tests"]) report.sections[dir] = measureSection(opts.root, dir);
console.log(markdown(report, opts.top));
if (opts.json) writeFileSync(opts.json, JSON.stringify(jsonReport(report, opts.all), null, 1) + "\n");
